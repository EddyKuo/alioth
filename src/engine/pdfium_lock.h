#pragma once

// PDFium 的行程級序列化鎖（ADR-005）。
//
// 為什麼需要它：PDFium 的文件把手**可以並存、不可以並行**。多份把手同時活著
// 完全正常，但只要兩條執行緒同時進 PDFium，就會非決定性地掉資料——實測是
// 同一組設定第一輪 60/60、第二輪 5/60，之後整個行程的開檔開始失敗。
// 壞掉的方式是安靜地少給資料，不是崩潰，所以「跑起來沒事」不能當作安全的證據。
// 量測表見 ADR-005。
//
// 產品目前有四個各自持有執行緒與把手的子系統：
//   PdfiumEngine（檢視器渲染，**以及列印**——列印自己持有一個引擎實體）
//   TextExtractor（文字、搜尋、建索引）
//   FormDocument（表單）
//   SignatureScanner（簽章）
// 其中列印與檢視是真的會同時動作的：列印是長時間大量渲染，而使用者在列印時
// 仍然會捲動。那正是兩條執行緒同時進 PDFium 的情境。
//
// **鎖的粒度是「一件工作」，不是「一次列印」。** 這一點是整個設計的關鍵：
// 每個子系統的工作單元本來就是有界的——一張 512×512 圖磚、一頁的文字層、
// 一次增量附加。列印同樣走圖磚（見 print_service.h，A0 圖在 600 dpi 下
// 整頁點陣是數 GB，本來就禁止整頁光柵化）。因此最壞情況是檢視器的圖磚
// 等一張列印圖磚，而不是等整份列印做完。
//
// 如果哪天有人讓列印改成整頁渲染，這把鎖就會變成「捲動卡住直到那一頁印完」。
// 那不是鎖的錯，是工作單元變得無界了——真正的修正是把它切回圖磚。
//
// **不可以在持有鎖的時候等另一個子系統。** 等待會直接死鎖，而且是在使用者的
// 機器上、在某個特定的交錯順序下才發生。工作本體只能呼叫 PDFium 與純運算，
// 回呼只能投遞（post），不能同步等待。

#include <mutex>

namespace alioth::engine {

// 取得行程級的 PDFium 鎖。整個行程只有一把，跨所有子系統與所有文件把手——
// 因為不安全的是 PDFium 的行程級狀態（字型與模組快取），不是個別把手。
//
// 用 recursive_mutex 而不是 mutex：同一條執行緒上，一個已加鎖的公開方法
// 呼叫另一個已加鎖的公開方法是很自然的寫法（例如 open() 內部先呼叫 close()），
// 而非遞迴鎖在那裡會直接自我死鎖。那種死鎖只在特定呼叫路徑上出現，
// 測試很容易漏掉，而代價是使用者的程式整個凍住。
// 遞迴鎖不會放寬跨執行緒的保證——別條執行緒仍然要等。
[[nodiscard]] std::recursive_mutex& pdfiumMutex();

// 包住一件工作的 RAII。放在各子系統工作者迴圈裡「執行工作」的那一行外面，
// 不要散在個別的 PDFium 呼叫點上——散開之後就無法保證一件工作內部的
// 一連串呼叫是原子的，而 PDFium 的狀態正是跨呼叫累積的。
class PdfiumGuard {
public:
    PdfiumGuard() : lock_(pdfiumMutex()) {}

    PdfiumGuard(const PdfiumGuard&) = delete;
    PdfiumGuard& operator=(const PdfiumGuard&) = delete;

private:
    std::lock_guard<std::recursive_mutex> lock_;
};

}  // namespace alioth::engine
